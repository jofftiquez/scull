// Generates src/styles/theme.css (the Tailwind v4 theme) from design/tokens.json.
//
//   pnpm --filter @scull/desktop tokens          # rewrite the file
//   node scripts/gen-theme.mjs --check           # exit 1 if the file is stale
//
// The design tokens are the single source of truth (D-16/D-17). Tailwind's default
// palette and every shadow utility are removed, so a class that isn't backed by a token fails
// to exist instead of quietly drifting from the design ("no shadows anywhere").

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const TOKENS_PATH = resolve(here, '../../../design/tokens.json');
export const THEME_PATH = resolve(here, '../src/styles/theme.css');

/** `textSecondary` -> `text-secondary`, `S0_regenerable` -> `s0-regenerable`. */
export function kebab(name) {
  return name
    .replace(/_/g, '-')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase();
}

/** The short tier key: `S0_regenerable` -> `s0`. */
function tierKey(name) {
  return name.split('_')[0].toLowerCase();
}

/**
 * The tier variables of one tier entry: the solid color (`bg-tier-s0`), the text on it, the
 * tier-colored text on the page (`fg`), the second stripe color of a pattern and the swatch
 * (a small dot that has to stand out from the page).
 * @param {string} k
 * @param {any} t
 * @returns {[string, string][]}
 */
function tierVars(k, t) {
  const key = tierKey(k);
  const solid = t.solid ?? t.fill;
  const vars = [
    [`--color-tier-${key}`, solid],
    [`--color-tier-${key}-text`, t.text],
    [`--color-tier-${key}-fg`, t.fg],
  ];
  if (t.stripe) vars.push([`--color-tier-${key}-stripe`, t.stripe]);
  vars.push([`--color-tier-${key}-swatch`, t.swatch ?? solid]);
  return vars;
}

/**
 * The dark palette (P5-UI-01): `dark.color` and `dark.tier` merged over the light values. Every
 * light color needs a dark value, so a new token can't silently keep its light value in dark.
 * @param {any} tokens
 * @returns {string[]} declarations, one per line
 */
export function darkDeclarations(tokens) {
  const dark = tokens.dark;
  if (!dark?.color) throw new Error('design/tokens.json: missing dark.color (P5-UI-01)');
  const missing = Object.keys(tokens.color).filter((k) => !(k in dark.color));
  const extra = Object.keys(dark.color).filter((k) => !(k in tokens.color));
  if (missing.length || extra.length) {
    throw new Error(`design/tokens.json: dark.color must have exactly the light keys (missing: ${missing.join(', ') || '-'}; unknown: ${extra.join(', ') || '-'})`);
  }
  const out = ['color-scheme: dark;'];
  for (const [k, v] of Object.entries(dark.color)) out.push(`--color-${kebab(k)}: ${v};`);
  for (const [k, light] of Object.entries(tokens.tier)) {
    const t = { ...light, ...(dark.tier?.[k] ?? {}) };
    for (const [name, v] of tierVars(k, t)) out.push(`${name}: ${v};`);
    out.push(`--tier-${tierKey(k)}-fill: ${t.fill};`);
  }
  return out;
}

/**
 * Render the theme stylesheet for a parsed tokens.json.
 * @param {any} tokens
 * @returns {string}
 */
export function renderTheme(tokens) {
  const out = [];
  const line = (s = '') => out.push(s);
  line('/* GENERATED by scripts/gen-theme.mjs from design/tokens.json. Do not edit by hand. */');
  line(`/* ${tokens.name} · tokens v${tokens.version} */`);
  line();
  // `static`: emit every variable even when no utility uses it (inline styles and SVGs read
  // them directly, e.g. var(--color-tier-s3-text)).
  line('@theme static {');
  line('  /* Only design tokens exist: no default palette, no shadows (D-16, D-17). */');
  line('  --color-*: initial;');
  line('  --shadow-*: initial;');
  line('  --inset-shadow-*: initial;');
  line('  --drop-shadow-*: initial;');
  line('  --text-shadow-*: initial;');
  line();
  for (const [k, v] of Object.entries(tokens.color)) {
    line(`  --color-${kebab(k)}: ${v};`);
  }
  line();
  for (const [k, t] of Object.entries(tokens.tier)) {
    for (const [name, v] of tierVars(k, t)) line(`  ${name}: ${v};`);
  }
  line();
  line(`  --font-sans: ${tokens.font.sans};`);
  line(`  --font-mono: ${tokens.font.mono};`);
  line();
  for (const [k, px] of Object.entries(tokens.font.scale)) {
    line(`  --text-${kebab(k)}: ${px}px;`);
  }
  line();
  for (const [k, px] of Object.entries(tokens.radius)) {
    line(`  --radius-${kebab(k)}: ${px}px;`);
  }
  line();
  // The spacing unit is 4 px, not Tailwind's 0.25rem: the root font size is the 14 px body
  // size, so rem-based spacing came out 12.5% small (`min-h-11` was 38.5 px, under the 44 px
  // touch target, and `px-6` was 21 px where the design says 24 px).
  line('  --spacing: 4px;');
  for (const [k, px] of Object.entries(tokens.space)) {
    line(`  --spacing-${kebab(k)}: ${px}px;`);
  }
  line(`  --spacing-touch: ${tokens.minTouchTarget}px;`);
  line('}');
  line();
  line('/* Tier patterns: tiers are never encoded by color alone (design/README.md). */');
  line(':root {');
  line('  color-scheme: light;');
  for (const [k, t] of Object.entries(tokens.tier)) {
    line(`  --tier-${tierKey(k)}-fill: ${t.fill};`);
  }
  line('}');
  line();
  // Dark (P5-UI-01): the system preference decides unless Settings forced a theme, which sets
  // <html data-theme="light|dark"> (src/lib/theme.ts). The same block is emitted twice because
  // a media query can't be OR-ed with an attribute selector.
  const dark = darkDeclarations(tokens);
  line('/* Dark theme: system preference, unless Settings > Appearance forces light or dark. */');
  line('@media (prefers-color-scheme: dark) {');
  line("  :root:not([data-theme='light']) {");
  for (const d of dark) line(`    ${d}`);
  line('  }');
  line('}');
  line("[data-theme='dark']:root {");
  for (const d of dark) line(`  ${d}`);
  line('}');
  line();
  return out.join('\n');
}

function main() {
  const tokens = JSON.parse(readFileSync(TOKENS_PATH, 'utf8'));
  const css = renderTheme(tokens);
  if (process.argv.includes('--check')) {
    const current = readFileSync(THEME_PATH, 'utf8');
    if (current !== css) {
      console.error('src/styles/theme.css is stale: run `pnpm --filter @scull/desktop tokens`');
      process.exit(1);
    }
    return;
  }
  writeFileSync(THEME_PATH, css);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
