// Generates src/styles/theme.css (the Tailwind v4 theme) from design/tokens.json.
//
//   pnpm --filter @scull/desktop tokens          # rewrite the file
//   node scripts/gen-theme.mjs --check           # exit 1 if the file is stale
//
// The design tokens are the single source of truth (HANDOVER §9, D-16/D-17). Tailwind's default
// palette and every shadow utility are removed, so a class that isn't backed by a token fails
// to exist instead of quietly drifting from the design ("no shadows anywhere").

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const TOKENS_PATH = resolve(here, '../../../design/tokens.json');
export const THEME_PATH = resolve(here, '../src/styles/theme.css');

/** `textSecondary` -> `text-secondary`, `S0_regenerable` -> `s0-regenerable`. */
export function kebab(name) {
  return name
    .replace(/_/g, '-')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase();
}

/** The short tier key: `S0_regenerable` -> `s0`. */
function tierKey(name) {
  return name.split('_')[0].toLowerCase();
}

/**
 * Render the theme stylesheet for a parsed tokens.json.
 * @param {any} tokens
 * @returns {string}
 */
export function renderTheme(tokens) {
  const out = [];
  const line = (s = '') => out.push(s);
  line('/* GENERATED by scripts/gen-theme.mjs from design/tokens.json. Do not edit by hand. */');
  line(`/* ${tokens.name} · tokens v${tokens.version} */`);
  line();
  // `static`: emit every variable even when no utility uses it (inline styles and SVGs read
  // them directly, e.g. var(--color-tier-s3-text)).
  line('@theme static {');
  line('  /* Only design tokens exist: no default palette, no shadows (D-16, D-17). */');
  line('  --color-*: initial;');
  line('  --shadow-*: initial;');
  line('  --inset-shadow-*: initial;');
  line('  --drop-shadow-*: initial;');
  line('  --text-shadow-*: initial;');
  line();
  for (const [k, v] of Object.entries(tokens.color)) {
    line(`  --color-${kebab(k)}: ${v};`);
  }
  line();
  for (const [k, t] of Object.entries(tokens.tier)) {
    const key = tierKey(k);
    const solid = t.solid ?? t.fill;
    line(`  --color-tier-${key}: ${solid};`);
    line(`  --color-tier-${key}-text: ${t.text};`);
  }
  line();
  line(`  --font-sans: ${tokens.font.sans};`);
  line(`  --font-mono: ${tokens.font.mono};`);
  line();
  for (const [k, px] of Object.entries(tokens.font.scale)) {
    line(`  --text-${kebab(k)}: ${px}px;`);
  }
  line();
  for (const [k, px] of Object.entries(tokens.radius)) {
    line(`  --radius-${kebab(k)}: ${px}px;`);
  }
  line();
  // The spacing unit is 4 px, not Tailwind's 0.25rem: the root font size is the 14 px body
  // size, so rem-based spacing came out 12.5% small (`min-h-11` was 38.5 px, under the 44 px
  // touch target, and `px-6` was 21 px where the design says 24 px).
  line('  --spacing: 4px;');
  for (const [k, px] of Object.entries(tokens.space)) {
    line(`  --spacing-${kebab(k)}: ${px}px;`);
  }
  line(`  --spacing-touch: ${tokens.minTouchTarget}px;`);
  line('}');
  line();
  line('/* Tier patterns: tiers are never encoded by color alone (design/README.md). */');
  line(':root {');
  for (const [k, t] of Object.entries(tokens.tier)) {
    line(`  --tier-${tierKey(k)}-fill: ${t.fill};`);
  }
  line('}');
  line();
  return out.join('\n');
}

function main() {
  const tokens = JSON.parse(readFileSync(TOKENS_PATH, 'utf8'));
  const css = renderTheme(tokens);
  if (process.argv.includes('--check')) {
    const current = readFileSync(THEME_PATH, 'utf8');
    if (current !== css) {
      console.error('src/styles/theme.css is stale: run `pnpm --filter @scull/desktop tokens`');
      process.exit(1);
    }
    return;
  }
  writeFileSync(THEME_PATH, css);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
