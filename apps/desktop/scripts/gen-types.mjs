// Generates src/bridge/generated.ts (the bridge's TypeScript types) from apps/desktop/schemas,
// the JSON Schemas of the Rust payload types (scull-desktop-bridge, `schemas::all`).
//
//   pnpm --filter @scull/desktop types            # rewrite the file
//   node scripts/gen-types.mjs --check            # exit 1 if it is stale
//
// Rust is the source of truth: change a payload in Rust, regenerate the schemas
// (SCULL_UPDATE_SCHEMAS=1 cargo test -p scull-desktop-bridge --test schemas), then this.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const here = dirname(fileURLToPath(import.meta.url));
export const SCHEMAS_DIR = resolve(here, '../schemas');
export const TYPES_PATH = resolve(here, '../src/bridge/generated.ts');

/** Every committed schema, by file stem, in name order. */
export function loadSchemas() {
  return readdirSync(SCHEMAS_DIR)
    .filter((f) => f.endsWith('.schema.json'))
    .sort()
    .map((f) => ({ stem: f.replace(/\.schema\.json$/, ''), schema: JSON.parse(readFileSync(resolve(SCHEMAS_DIR, f), 'utf8')) }));
}

/** Drop siblings of `$ref` (schemars puts descriptions there), which would otherwise make the
 * compiler emit a numbered copy of the referenced type for each use. */
function bareRefs(node) {
  if (Array.isArray(node)) return node.map(bareRefs);
  if (!node || typeof node !== 'object') return node;
  if (typeof node.$ref === 'string') return { $ref: node.$ref };
  return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, bareRefs(v)]));
}

/**
 * One schema holding every payload: each payload becomes a definition named by its title, all
 * `$defs` are merged (a name defined differently by two payloads is an error), and the root
 * lists every payload so each is emitted once.
 */
export function combinedSchema() {
  const defs = {};
  const put = (name, def, from) => {
    const clean = bareRefs(def);
    if (name in defs && JSON.stringify(defs[name]) !== JSON.stringify(clean)) {
      throw new Error(`definition ${name} differs between payloads (${from})`);
    }
    defs[name] = clean;
  };
  const properties = {};
  for (const { stem, schema } of loadSchemas()) {
    const { $defs = {}, title, ...root } = schema;
    delete root.$schema;
    delete root.$id;
    for (const [name, def] of Object.entries($defs)) put(name, def, stem);
    put(title, { ...root, title }, stem);
    properties[title] = { $ref: `#/$defs/${title}` };
  }
  return {
    title: 'BridgePayloads',
    description: 'Every payload of the desktop bridge, by type name.',
    type: 'object',
    additionalProperties: false,
    properties,
    required: Object.keys(properties),
    $defs: defs,
  };
}

/**
 * Render the TypeScript module.
 * @returns {Promise<string>}
 */
export async function renderTypes() {
  const ts = await compile(combinedSchema(), 'BridgePayloads', {
    bannerComment:
      '// GENERATED by scripts/gen-types.mjs from apps/desktop/schemas (the Rust payload types).\n' +
      '// Do not edit by hand.',
    additionalProperties: false,
    strictIndexSignatures: true,
    unreachableDefinitions: true,
    declareExternallyReferenced: true,
    format: true,
  });
  return ts.trimEnd() + '\n';
}

async function main() {
  const ts = await renderTypes();
  if (process.argv.includes('--check')) {
    if (readFileSync(TYPES_PATH, 'utf8') !== ts) {
      console.error('src/bridge/generated.ts is stale: run `pnpm --filter @scull/desktop types`');
      process.exit(1);
    }
    return;
  }
  writeFileSync(TYPES_PATH, ts);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
