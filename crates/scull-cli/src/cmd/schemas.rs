//! Published JSON Schemas for the read-only commands (CLI-01), committed under
//! `crates/scull-cli/schemas/` and checked against real output in the tests (regenerate with
//! `SCULL_BLESS=1 cargo test -p scull-cli --test read_only`).
//!
//! Each command has a `--json` document schema (`<name>.schema.json`, the versioned
//! [`Envelope`](crate::output::json::Envelope)) and an `--ndjson` line schema
//! (`<name>.ndjson.schema.json`): every line is `{schema, version, type, data}` where `type`
//! picks the shape of `data`.
//!
//! Every command that prints NDJSON publishes a line schema (#247). Single-document commands
//! (`status`, `doctor`, `init`, `check`, `rules`, ...) print one record whose `data` is their
//! `--json` payload ([`single_record_schema`]); their document schemas are generated by their
//! own tests, their line schemas here ([`line_schemas`]). `tests/ndjson_schemas.rs` runs every
//! command with `--ndjson` and fails when one prints lines without a published schema.

use crate::output::json::{SCHEMA_ID_PATTERN, SchemaId, document_schema};
use schemars::JsonSchema;
use serde::Serialize;

/// One NDJSON line: the envelope fields plus an adjacently tagged record (`type` + `data`).
/// Only used to generate schemas; output is written by
/// [`NdjsonWriter`](crate::output::json::NdjsonWriter), which produces the same shape.
#[derive(Debug, Serialize, JsonSchema)]
pub struct NdjsonLine<T> {
    /// `scull/<name>@<major>`.
    #[schemars(regex(pattern = SCHEMA_ID_PATTERN))]
    pub schema: String,
    /// The scull version that wrote it.
    pub version: String,
    /// `type` and `data`.
    #[serde(flatten)]
    pub record: T,
}

/// The NDJSON line schema for records `T`, titled and pinned to `id`.
pub fn ndjson_schema<T: JsonSchema>(id: SchemaId) -> serde_json::Value {
    let mut v = serde_json::to_value(schemars::schema_for!(NdjsonLine<T>)).unwrap_or_default();
    v["title"] = format!("{id} (NDJSON line)").into();
    v["description"] = format!(
        "One line of `--ndjson` output with schema {id}: `type` selects the shape of `data`."
    )
    .into();
    v["properties"]["schema"]["const"] = id.to_string().into();
    v
}

/// The one record of a single-document command's `--ndjson` output: `type` is fixed per
/// command and `data` is the same payload as in its `--json` document. Only used to generate
/// schemas; output is written by [`emit_machine`](super::emit_machine).
#[derive(Debug, Serialize, JsonSchema)]
pub struct SingleRecord<T> {
    /// The record type (one value per command, e.g. `status`).
    #[serde(rename = "type")]
    pub kind: String,
    /// The payload, as in the command's `--json` document.
    pub data: T,
}

/// The NDJSON line schema of a single-document command whose one record has type `kind`.
pub fn single_record_schema<T: JsonSchema>(id: SchemaId, kind: &str) -> serde_json::Value {
    let mut v = ndjson_schema::<SingleRecord<T>>(id);
    v["properties"]["type"]["const"] = kind.into();
    v["additionalProperties"] = false.into();
    v
}

/// The file name of a schema: `scull/<name>@1` → `<name>.schema.json` (`ndjson`: the
/// `<name>.ndjson.schema.json` line schema).
pub fn file_name(id: SchemaId, ndjson: bool) -> String {
    let name = id.to_string();
    let short = name
        .trim_start_matches("scull/")
        .split('@')
        .next()
        .unwrap_or_default()
        .to_owned();
    if ndjson {
        format!("{short}.ndjson.schema.json")
    } else {
        format!("{short}.schema.json")
    }
}

/// NDJSON line schemas of the commands whose `--json` document schema is generated and
/// checked by that command's own tests (`(file name, schema)`); CLI-01, #247.
pub fn line_schemas() -> Vec<(String, serde_json::Value)> {
    use super::{agent, check, doctor, init, insights, rules, schedule, status};
    use crate::large_files;
    let single = |id: SchemaId, schema: serde_json::Value| (file_name(id, true), schema);
    vec![
        single(
            doctor::DOCTOR_SCHEMA,
            single_record_schema::<doctor::DoctorReport>(doctor::DOCTOR_SCHEMA, "doctor"),
        ),
        single(
            init::INIT_SCHEMA,
            single_record_schema::<init::InitReport>(init::INIT_SCHEMA, "init"),
        ),
        single(
            status::STATUS_SCHEMA,
            single_record_schema::<status::StatusReport>(status::STATUS_SCHEMA, "status"),
        ),
        single(
            check::CHECK_SCHEMA,
            single_record_schema::<check::CheckReport>(check::CHECK_SCHEMA, "check"),
        ),
        single(
            schedule::SCHEDULE_SCHEMA,
            single_record_schema::<schedule::ScheduleReport>(schedule::SCHEDULE_SCHEMA, "schedule"),
        ),
        single(
            rules::RULES_LIST_SCHEMA,
            single_record_schema::<rules::RulesList>(rules::RULES_LIST_SCHEMA, "rules"),
        ),
        single(
            rules::RULES_VALIDATE_SCHEMA,
            single_record_schema::<rules::RulesValidation>(
                rules::RULES_VALIDATE_SCHEMA,
                "validation",
            ),
        ),
        single(
            insights::INSIGHTS_SCHEMA,
            single_record_schema::<scull_insights::InsightsReport>(
                insights::INSIGHTS_SCHEMA,
                "insights",
            ),
        ),
        single(
            agent::AGENT_SCHEMA,
            single_record_schema::<agent::AgentReport>(agent::AGENT_SCHEMA, "agent"),
        ),
        single(
            large_files::LARGE_FILES_SCHEMA,
            ndjson_schema::<large_files::LargeFilesRecord>(large_files::LARGE_FILES_SCHEMA),
        ),
    ]
    .into_iter()
    .chain(phase2_line_schemas())
    .collect()
}

/// Line schemas of the `phase2` commands (`clean`, `clean caches`, `clean --purge-quarantine`,
/// `history`, `restore`, `data`): each prints one record whose `data` is its `--json` payload.
fn phase2_line_schemas() -> Vec<(String, serde_json::Value)> {
    use super::{clean, clean_caches, data, history, restore};
    fn single<T: JsonSchema>(id: SchemaId, kind: &str) -> (String, serde_json::Value) {
        (file_name(id, true), single_record_schema::<T>(id, kind))
    }
    vec![
        single::<clean::CleanPlanReport>(clean::CLEAN_PLAN_SCHEMA, "plan"),
        single::<clean::CleanRunReport>(clean::CLEAN_RUN_SCHEMA, "run"),
        single::<clean_caches::CleanCachesReport>(clean_caches::CLEAN_CACHES_SCHEMA, "caches"),
        single::<restore::PurgeReport>(restore::PURGE_SCHEMA, "purge"),
        single::<restore::RestoreReport>(restore::RESTORE_SCHEMA, "restore"),
        single::<history::HistoryReport>(history::HISTORY_SCHEMA, "history"),
        single::<history::OperationDetail>(history::HISTORY_OPERATION_SCHEMA, "operation"),
        single::<data::DataShowReport>(data::DATA_SHOW_SCHEMA, "data"),
        single::<data::DataExportReport>(data::DATA_EXPORT_SCHEMA, "data"),
        single::<data::DataPurgeReport>(data::DATA_PURGE_SCHEMA, "data"),
    ]
}

/// Every committed command schema this module generates: `(file name, schema)`.
pub fn all() -> Vec<(String, serde_json::Value)> {
    use super::{caches, projects, scan, worktrees};
    let mut out = Vec::new();
    let mut add = |id: SchemaId, doc: serde_json::Value, nd: serde_json::Value| {
        out.push((file_name(id, false), doc));
        out.push((file_name(id, true), nd));
    };
    add(
        scan::SCAN_SCHEMA,
        document_schema::<scull_engine::ScanReport>(scan::SCAN_SCHEMA),
        ndjson_schema::<scan::ScanRecord>(scan::SCAN_SCHEMA),
    );
    add(
        projects::PROJECTS_SCHEMA,
        document_schema::<projects::ProjectsReport>(projects::PROJECTS_SCHEMA),
        ndjson_schema::<projects::ProjectsRecord>(projects::PROJECTS_SCHEMA),
    );
    add(
        projects::PROJECT_SCHEMA,
        document_schema::<projects::ProjectInspect>(projects::PROJECT_SCHEMA),
        ndjson_schema::<projects::ProjectRecord>(projects::PROJECT_SCHEMA),
    );
    add(
        worktrees::WORKTREES_SCHEMA,
        document_schema::<worktrees::WorktreesReport>(worktrees::WORKTREES_SCHEMA),
        ndjson_schema::<worktrees::WorktreesRecord>(worktrees::WORKTREES_SCHEMA),
    );
    add(
        worktrees::WORKTREE_SCHEMA,
        document_schema::<scull_engine::WorktreeReport>(worktrees::WORKTREE_SCHEMA),
        ndjson_schema::<worktrees::WorktreeRecord>(worktrees::WORKTREE_SCHEMA),
    );
    add(
        worktrees::REGISTRATION_SCHEMA,
        document_schema::<worktrees::RegistrationReport>(worktrees::REGISTRATION_SCHEMA),
        ndjson_schema::<worktrees::RegistrationRecord>(worktrees::REGISTRATION_SCHEMA),
    );
    add(
        caches::CACHES_SCHEMA,
        document_schema::<caches::CachesDocument>(caches::CACHES_SCHEMA),
        ndjson_schema::<caches::CachesRecord>(caches::CACHES_SCHEMA),
    );
    {
        use super::doctor_report::{DOCTOR_REPORT_SCHEMA, ShareableReport};
        add(
            DOCTOR_REPORT_SCHEMA,
            document_schema::<ShareableReport>(DOCTOR_REPORT_SCHEMA),
            single_record_schema::<ShareableReport>(DOCTOR_REPORT_SCHEMA, "doctor-report"),
        );
    }
    out.extend(line_schemas());
    out
}
