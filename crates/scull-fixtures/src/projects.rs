//! Project markers and lockfiles for Cargo, npm and pnpm projects, and their build artifacts.

use crate::error::Result;
use crate::fixture::Fixture;
use std::path::Path;

/// Which Node lockfile a project has (FX-CLS-05).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NodeLock {
    /// `package-lock.json`.
    Npm,
    /// `pnpm-lock.yaml`.
    Pnpm,
    /// No lockfile at all.
    None,
}

/// Contents of `CACHEDIR.TAG` as Cargo writes it into `target/`.
pub const CACHEDIR_TAG: &str = "Signature: 8a477f597d28d172789f06886806bc55\n\
# This file is a cache directory tag created by cargo.\n\
# For information about cache directory tags see https://bford.info/cachedir/\n";

impl Fixture {
    /// A Cargo binary project at `rel`: `Cargo.toml`, `Cargo.lock` and `src/main.rs`.
    pub fn cargo_project(&mut self, rel: impl AsRef<Path>, name: &str) -> Result<&mut Self> {
        let rel = rel.as_ref();
        self.file(
            rel.join("Cargo.toml"),
            format!(
                "[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n\
                 [dependencies]\n"
            ),
        )?
        .file(
            rel.join("Cargo.lock"),
            format!(
                "# This file is automatically @generated by Cargo.\n\
                 # It is not intended for manual editing.\nversion = 4\n\n\
                 [[package]]\nname = \"{name}\"\nversion = \"0.1.0\"\n"
            ),
        )?
        .file(
            rel.join("src").join("main.rs"),
            "fn main() {\n    println!(\"hello\");\n}\n",
        )
    }

    /// A Cargo `target/` directory inside the project at `project_rel`, with `CACHEDIR.TAG`,
    /// `.rustc_info.json`, fingerprints and a `debug/<name>` binary of `binary_size` bytes.
    pub fn cargo_target(
        &mut self,
        project_rel: impl AsRef<Path>,
        name: &str,
        binary_size: u64,
    ) -> Result<&mut Self> {
        let t = project_rel.as_ref().join("target");
        let fp = t
            .join("debug")
            .join(".fingerprint")
            .join(format!("{name}-0123456789abcdef"));
        self.file(t.join("CACHEDIR.TAG"), CACHEDIR_TAG)?
            .file(
                t.join(".rustc_info.json"),
                r#"{"rustc_fingerprint":0,"outputs":{}}"#,
            )?
            .file(fp.join(format!("bin-{name}")), "0123456789abcdef")?
            .file(
                fp.join(format!("bin-{name}.json")),
                r#"{"rustc":0,"features":"[]"}"#,
            )?
            .file(t.join("debug").join(format!("{name}.d")), "deps\n")?
            .file_of_size(t.join("debug").join(name), binary_size)
    }

    /// A Node project at `rel`: `package.json` plus the chosen lockfile.
    pub fn npm_project(
        &mut self,
        rel: impl AsRef<Path>,
        name: &str,
        lock: NodeLock,
    ) -> Result<&mut Self> {
        let rel = rel.as_ref();
        self.file(
            rel.join("package.json"),
            format!(
                "{{\n  \"name\": \"{name}\",\n  \"version\": \"1.0.0\",\n  \"private\": true\n}}\n"
            ),
        )?;
        match lock {
            NodeLock::Npm => self.file(
                rel.join("package-lock.json"),
                format!(
                    "{{\n  \"name\": \"{name}\",\n  \"version\": \"1.0.0\",\n  \
                     \"lockfileVersion\": 3,\n  \"requires\": true,\n  \"packages\": {{}}\n}}\n"
                ),
            ),
            NodeLock::Pnpm => self.file(
                rel.join("pnpm-lock.yaml"),
                "lockfileVersion: '9.0'\n\nsettings:\n  autoInstallPeers: true\n\nimporters:\n\n  .: {}\n",
            ),
            NodeLock::None => Ok(self),
        }
    }

    /// A `node_modules/` inside the project at `project_rel` holding the given packages, each
    /// with a `package.json` and an `index.js`.
    pub fn node_modules(
        &mut self,
        project_rel: impl AsRef<Path>,
        packages: &[&str],
    ) -> Result<&mut Self> {
        let nm = project_rel.as_ref().join("node_modules");
        self.dir(&nm)?;
        for p in packages {
            let d = nm.join(p);
            self.file(
                d.join("package.json"),
                format!("{{\"name\":\"{p}\",\"version\":\"1.0.0\",\"main\":\"index.js\"}}\n"),
            )?
            .file(d.join("index.js"), format!("module.exports = '{p}';\n"))?;
        }
        Ok(self)
    }

    /// A pnpm workspace root at `rel`: `package.json`, `pnpm-workspace.yaml` (`packages/*`) and
    /// `pnpm-lock.yaml`, plus one `packages/<name>/package.json` per entry in `packages`.
    pub fn pnpm_workspace(
        &mut self,
        rel: impl AsRef<Path>,
        name: &str,
        packages: &[&str],
    ) -> Result<&mut Self> {
        let rel = rel.as_ref();
        self.npm_project(rel, name, NodeLock::Pnpm)?.file(
            rel.join("pnpm-workspace.yaml"),
            "packages:\n  - 'packages/*'\n",
        )?;
        for p in packages {
            self.npm_project(rel.join("packages").join(p), p, NodeLock::None)?;
        }
        Ok(self)
    }
}
