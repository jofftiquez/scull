#!/usr/bin/env python3
"""Draft a CHANGELOG section from the merged commits since the last release (P4-REL-01).

Offline: reads `git log` only. Squash-merge subjects look like
``[P3-UI-02] Storage Explorer: ... (#123)``; the key's area picks the heading, the trailing
``(#n)`` becomes a link. Evidence-only commits (``[skip ci]``), reverts of commits in the same
range and merge commits are left out. The output is a **draft**: the maintainer edits it
(wording, "Known limitations") before it goes into CHANGELOG.md, because dist copies the
``## <version>`` section into the GitHub release notes.

Usage::

    python3 scripts/release/changelog.py --version 1.0.0 --since v0.1.0-alpha.1 [--until HEAD]
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPO_URL = "https://github.com/jofftiquez/scull"

# Area code (the part after `Pn-`) -> heading. First match wins; unknown areas go to "Other".
SECTIONS: "OrderedDict[str, tuple[str, ...]]" = OrderedDict(
    [
        ("Safety", ("SAFE", "EXEC", "QC", "TRASH", "JOURNAL", "AUDIT", "RESTORE", "LOCK")),
        ("Desktop app", ("UI", "E2E", "A11Y", "DESK", "MENU", "CHART", "DARK", "TRAY")),
        ("CLI", ("CLI",)),
        ("MCP and agents", ("MCP", "AI", "AGENT")),
        ("Scanning and detection", ("SCAN", "DET", "GIT", "ENG", "PLAT", "WIN", "MEASURE", "FX")),
        ("Insights and monitoring", ("INS", "PRO", "DIGEST", "AUTO")),
        ("Release, packaging and CI", ("REL", "CI", "OPS")),
        ("Research", ("RES",)),
    ]
)
OTHER = "Other"

KEY = re.compile(r"^\[(?P<key>[A-Z0-9][A-Z0-9-]*)\]\s*(?P<title>.*)$")
PR = re.compile(r"\s*\(#(\d+)\)\s*$")


def git_subjects(since: str | None, until: str, cwd: Path) -> list[str]:
    rng = f"{since}..{until}" if since else until
    out = subprocess.run(
        ["git", "log", "--no-merges", "--format=%s", rng],
        cwd=cwd, check=True, capture_output=True, text=True,
    ).stdout
    return [line for line in out.splitlines() if line.strip()]


def area(key: str) -> str:
    parts = key.split("-")
    # `P3-UI-02` -> UI; `P1-WIN-CI` -> WIN; `REL` -> REL.
    code = parts[1] if len(parts) > 1 and re.fullmatch(r"P\d+", parts[0]) else parts[0]
    for heading, codes in SECTIONS.items():
        if code in codes:
            return heading
    return OTHER


def entries(subjects: list[str]) -> "OrderedDict[str, list[str]]":
    reverted = {m.group(1) for s in subjects if (m := re.match(r'^Revert "(.*)"$', s))}
    grouped: "OrderedDict[str, list[str]]" = OrderedDict((h, []) for h in [*SECTIONS, OTHER])
    seen = set()
    for s in reversed(subjects):  # oldest first
        if "[skip ci]" in s or s.startswith("Revert \"") or s in reverted:
            continue
        m = KEY.match(s)
        if m:
            heading, title = area(m.group("key")), m.group("title")
        elif cm := re.match(r"^(chore|docs|ci|build|test)(\(.+\))?:", s):
            ci = cm.group(1) in ("ci", "build")
            heading = "Release, packaging and CI" if ci else OTHER
            title = s.split(":", 1)[1].strip()
        else:
            heading, title = OTHER, s
        # Only the trailing "(#n)" is the squash-merged PR; other "(#n)" are issue references.
        prs = PR.findall(title)
        title = PR.sub("", title, count=1).strip()
        if not title or title.lower() in seen:
            continue
        seen.add(title.lower())
        link = f" ([#{prs[-1]}]({REPO_URL}/pull/{prs[-1]}))" if prs else ""
        grouped[heading].append(f"- {title}{link}")
    return grouped


def render(version: str, grouped: "OrderedDict[str, list[str]]") -> str:
    lines = [f"## {version}", "", "> Draft generated by scripts/release/changelog.py: edit before release.", ""]
    for heading, items in grouped.items():
        if items:
            lines += [f"### {heading}", "", *items, ""]
    lines += ["### Known limitations", "", "- (fill in)", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--version", required=True)
    ap.add_argument("--since", help="previous release tag or commit (default: the whole history)")
    ap.add_argument("--until", default="HEAD")
    ap.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    a = ap.parse_args()
    try:
        subjects = git_subjects(a.since, a.until, a.root)
    except subprocess.CalledProcessError as e:
        print(f"changelog.py: git log failed: {e.stderr.strip()}", file=sys.stderr)
        return 1
    print(render(a.version.removeprefix("v"), entries(subjects)), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
